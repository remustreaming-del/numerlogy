// Regenerates lib/couple/calibration.ts: score percentiles against simulated random couples.
// node --experimental-strip-types scripts/calibrate-couple.mjs [couplesPerSet]
//
// Couples are drawn the way real couples are distributed in age: person A is born in
// 1965–2006, person B within a few years of A (normal, σ ≈ 4 years). Dates, times and
// Mongolian birthplaces are uniform. A score of 70 then means «stronger than 70% of
// these couples».
import { writeFile } from "node:fs/promises";
import { calculateNatalChart } from "../lib/astrology.ts";
import { MONGOLIAN_CITIES } from "../lib/cities.ts";
import { calibrationSet, crossAspects, METRICS, rawScores, signLinks } from "../lib/couple/synastry.ts";

const COUNT = Number(process.argv[2] ?? 4000);
let seed = 20261025;
const random = () => (seed = (seed * 48271) % 2147483647) / 2147483647;
const gaussian = () => Math.sqrt(-2 * Math.log(random() || 1e-9)) * Math.cos(2 * Math.PI * random());
const pad = (value) => String(value).padStart(2, "0");
const person = (year, unknownTime) => ({
  name: "Тест", birthDate: `${year}-${pad(1 + Math.floor(random() * 12))}-${pad(1 + Math.floor(random() * 28))}`,
  birthTime: `${pad(Math.floor(random() * 24))}:${pad(Math.floor(random() * 60))}`,
  cityId: MONGOLIAN_CITIES[Math.floor(random() * MONGOLIAN_CITIES.length)].id, unknownTime,
});

const sets = { known2: [false, false], known1: [false, true], known0: [true, true] };
const output = {};
for (const [name, [unknownA, unknownB]] of Object.entries(sets)) {
  const values = Object.fromEntries(METRICS.map((metric) => [metric, []]));
  for (let index = 0; index < COUNT; index++) {
    const yearA = 1965 + Math.floor(random() * 42);
    const yearB = Math.min(2007, Math.max(1950, Math.round(yearA + gaussian() * 4)));
    const a = calculateNatalChart(person(yearA, unknownA)), b = calculateNatalChart(person(yearB, unknownB));
    if (calibrationSet(a, b) !== name) throw new Error("set mismatch");
    const raw = rawScores(crossAspects(a, b), signLinks(a, b));
    for (const metric of METRICS) values[metric].push(raw[metric]);
  }
  output[name] = Object.fromEntries(METRICS.map((metric) => {
    const sorted = values[metric].sort((x, y) => x - y);
    return [metric, Array.from({ length: 21 }, (_, step) => Math.round(sorted[Math.min(sorted.length - 1, Math.round((step / 20) * (sorted.length - 1)))] * 1000) / 1000)];
  }));
  console.error(`${name}: ${COUNT} couples`);
}

const body = Object.entries(output).map(([set, metrics]) => `  ${set}: {\n${Object.entries(metrics).map(([metric, list]) => `    ${metric}: [${list.join(", ")}],`).join("\n")}\n  },`).join("\n");
await writeFile(new URL("../lib/couple/calibration.ts", import.meta.url), `// Generated by scripts/calibrate-couple.mjs (${COUNT} simulated couples per set). Do not edit by hand.
// Raw score at every 5th percentile (0, 5, … 100) of simulated random couples, per metric.
// known2: both birth times known · known1: one unknown · known0: both unknown.
export const CALIBRATION = {
${body}
} as const;
`);
console.error("lib/couple/calibration.ts written");
